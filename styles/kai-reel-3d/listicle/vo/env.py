# env.py: per-frame (30 fps) loudness envelope of each voice stem → src/vo_env.js (ENV_K = Kai, ENV_C = Clawd; 0..1,
# normalised to the 95th pct of that voice's voiced frames). Drives the mouths: Kai via kai-talk.js voMouth, Clawd via o.talk.
import numpy as np, subprocess, json
FPS, SR = 30, 48000
def env(p):
    raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', p, '-f', 's16le', '-ac', '1', '-ar', str(SR), '-'])
    x = np.frombuffer(raw, np.int16).astype(np.float32) / 32768
    hop = SR // FPS; n = len(x) // hop
    rms = np.array([np.sqrt(np.mean(x[max(0, f * hop - hop // 2): f * hop + hop // 2] ** 2) + 1e-12) for f in range(n)])
    db = 20 * np.log10(rms + 1e-9); voiced = db > db.max() - 30
    return np.clip(rms / np.percentile(rms[voiced], 95), 0, 1)
import os
K = env('vo/vo_kai.wav'); C = env('vo/vo_clawd.wav') if os.path.exists('vo/vo_clawd.wav') else np.zeros_like(K)   # reel63 listicle: narrator only
r = lambda a: json.dumps([round(float(v), 3) for v in a])
open('src/vo_env.js', 'w').write('// generated by vo/env.py: VO loudness per frame (30 fps), 0..1, per voice stem.\n'
  f'const ENV_FPS = {FPS};\nconst ENV_K = {r(K)};\nconst ENV_C = {r(C)};\n')
print('frames', len(K), len(C))
