// "Thử góc máy": a director's note about the camera -> 3-4 camera variants rendered by the film's own engine (headless
// Chrome, real GPU), side by side, with a top view and wall numbers; then the picked one goes into the camera anchors.
//   node styles/stick-man/tools/run/camtry.mjs "đoạn đua xe, máy quay dính tường nhà, nâng lên chút"
//        [--film films/<slug>] [--out <dir>] [--frames A-B] [--variants v.json] [--w 360 --h 640] [--dry]
//   node styles/stick-man/tools/run/camtry.mjs pick <out dir> <V1> [--dry]
// The first line printed is the readback ("Em hiểu là: phim …, đoạn …, xem cả đoạn khung A-B, phương án đổi …, máy quay
// …"). The film defaults to the newest one in ./films; the segment, takes and anchors come from its generated act tables
// (camtry-core.mjs). The clip is always the whole segment at 30 fps (--frames A-B narrows it, inside the segment); a
// narrower note ("take 2", "đoạn đầu …", "ngân hàng thứ hai") changes only that take, and the clip marks those frames.
// Writes to --out (default <film>/review/camtry/<SEG>-<A>-<B>/): variants.mp4, top.jpg, poster.jpg, camtry.json (the
// readback, the variants and the numbers per variant over the changed frames), section.html (clip, top view, numbers, a
// pick box for the stage page).
// `pick` sets the anchors' dz to the previs run's dz plus the variant's lift (picking twice never stacks; V0 puts them
// back), keeps <xfer>.bak, reruns every generator that reads the anchors (the `// generated by` line of <round>/gen/*.js)
// and restores the anchors and the generated files when one fails. It only writes inside the film folder. --dry prints
// the change only. Film and kit files are read only until `pick`.
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
import { run } from '../../../../kit/env.mjs';
import { serveFiles, launchGpu } from '#tools/render/pageserver.mjs';
import { filmIndex, findFilm, resolve, movesOf, variantsFromWords, readback, applyPick, refusals, formatSpec, parseGen, recommend } from './camtry-core.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
if (!argv.length || argv.includes('--help')) {
  console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').filter(l => l.startsWith('//')).map(l => l.slice(3)).join('\n'));
  process.exit(argv.length ? 0 : 2);
}
// --dry is a switch: bare, or followed by 1/true (0/false turn it off); every other flag takes a value
const SWITCH = /^(1|0|true|false)$/, flag = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 ? argv[i + 1] : d; };
const dry = argv.includes('--dry') && !/^(0|false)$/.test(argv[argv.indexOf('--dry') + 1] ?? '');
const words = argv.filter((a, i) => !a.startsWith('--') && !(i && argv[i - 1].startsWith('--') && (argv[i - 1] !== '--dry' || SWITCH.test(a))));

const real = p => fs.realpathSync(p), inside = (dir, p) => { const d = real(dir), f = real(p); return f.startsWith(d + path.sep); };
async function pick(outDir, id) {
  const J = JSON.parse(fs.readFileSync(path.join(outDir, 'camtry.json'), 'utf8')), v = J.variants.find(x => x.id === id);
  if (!v) { console.error(`no variant ${id} in ${outDir} (${J.variants.map(x => x.id).join(', ')})`); process.exit(2); }
  if (!J.xfer) { console.error(`đoạn ${J.seg} không có file neo xfer: máy quay nằm trong file act, sửa tay theo số ở camtry.json`); process.exit(1); }
  const film = J.film, round = path.dirname(path.dirname(J.xfer));
  if (!fs.existsSync(path.join(film, 'reel.js')) || !fs.existsSync(J.xfer) || !inside(film, J.xfer) || path.basename(path.dirname(J.xfer)) !== 'xfer' || !/^r\d+$/.test(path.basename(round))) {
    console.error(`pick: ${J.xfer} không phải file neo <round>/xfer/ trong phim ${film}; không ghi gì`); process.exit(2);
  }
  const base = Object.fromEntries((J.anchors ?? []).map(a => [`${a.f0}-${a.f1}`, a.dz ?? 0]));
  const before = fs.readFileSync(J.xfer, 'utf8'), res = applyPick(JSON.parse(before), v, J.change ?? J.window, base);
  if (!res.ok) { console.error(`${v.label}: chưa áp tự động được: ${res.unsupported.join('; ')}`); process.exit(1); }
  if (!res.changed.length) { console.log(`${v.label}: neo đã đúng, không có gì đổi`); return; }
  for (const c of res.changed) console.log(`neo ${c.f0}-${c.f1 - 1}: dz ${c.dz0} -> ${c.dz} (cả cửa sổ neo, khung ${c.f0}-${c.f1 - 1})`);
  if (dry) return;
  const rel = path.relative(film, J.xfer), repo = path.dirname(path.dirname(film)), gens = [];
  for (const f of fs.readdirSync(path.join(round, 'gen')).filter(x => x.endsWith('.js'))) {
    const file = path.join(round, 'gen', f), head = fs.readFileSync(file, 'utf8').split('\n', 1)[0], g = parseGen(head);
    if (!g.tool || !head.includes(` ${rel}`)) continue;
    const tool = path.join(film, g.tool);
    if (!fs.existsSync(tool) || !inside(film, tool)) { console.error(`pick: generator ${g.tool} nằm ngoài phim; không ghi gì`); process.exit(2); }
    gens.push({ file, tool, args: g.seg && g.seg !== 'from' ? [g.seg] : [] });
  }
  const saved = new Map(gens.map(g => [g.file, fs.readFileSync(g.file)]));
  fs.writeFileSync(`${J.xfer}.bak`, before);
  fs.writeFileSync(J.xfer, formatSpec(res.spec));
  for (const g of gens) {
    console.log('regenerate:', path.relative(repo, g.tool), g.args.join(' '));
    const r = run('node', [g.tool, ...g.args], { cwd: repo });
    if (r.status) {
      fs.writeFileSync(J.xfer, before); for (const [f, b] of saved) fs.writeFileSync(f, b);
      console.error(`pick: ${path.basename(g.tool)} lỗi (${r.status}); đã trả neo và file act về như cũ`); process.exit(r.status);
    }
  }
}

async function camtry(request) {
  const filmDir = flag('film') ? path.resolve(flag('film')) : findFilm(path.resolve('films'), request);
  if (!filmDir) { console.error('no film in ./films (give --film films/<slug>)'); process.exit(2); }
  const index = filmIndex(filmDir), r = resolve(request, index), moves = movesOf(request);
  if (r.seg && flag('frames')) {
    const m = String(flag('frames')).match(/^(\d+)-(\d+)$/), [a, b] = m ? [+m[1], +m[2]] : [NaN, NaN];
    if (!(a <= b && a >= r.seg.frames[0] && b <= r.seg.frames[1])) { console.error(`--frames ${flag('frames')}: cần A-B, A <= B, trong đoạn ${r.seg.id} ${r.seg.frames.join('-')}`); process.exit(2); }
    if (r.change[1] < a || r.change[0] > b) { console.error(`--frames ${a}-${b} không chứa khung đổi ${r.change.join('-')}`); process.exit(2); }
    r.window = [a, b]; r.change = [Math.max(a, r.change[0]), Math.min(b, r.change[1])];
  }
  console.log(readback(r, moves));
  if (!r.seg) process.exit(1);
  const V = flag('variants') ? JSON.parse(fs.readFileSync(flag('variants'), 'utf8')) : variantsFromWords(request);
  const [A, B] = r.window, [C0, C1] = r.change, OUT = path.resolve(flag('out', path.join(filmDir, 'review', 'camtry', `${r.seg.id}-${C0}-${C1}`)));
  fs.mkdirSync(OUT, { recursive: true });
  const cuts = r.seg.cuts.filter(c => c > A && c <= B);
  const J = { request, readback: readback(r, moves), film: filmDir, seg: r.seg.id, segFrames: r.seg.frames, window: r.window, change: r.change,
    take: r.take, takes: r.takes.map(t => ({ n: t.n, frames: t.frames })), cuts, xfer: r.seg.xfer, anchors: r.anchors, boot: r.seg.boot, why: r.why, moves,
    variants: V.map(v => ({ ...v, applies: !refusals(v).length })) };
  fs.writeFileSync(path.join(OUT, 'camtry.json'), JSON.stringify(J, null, 1));
  for (const v of J.variants) console.log(' ', v.label, v.applies ? '' : '(xem được, áp tay)');
  if (dry) { console.log('out', OUT); return; }

  const repo = path.dirname(path.dirname(filmDir)), TW = 270, TH = 480, BAR = 40, STRIP = 22;
  const server = await serveFiles(repo, { mounts: { '/__camtry/': HERE } }), browser = await launchGpu();
  const kill = setTimeout(async () => { console.error('camtry: 9 min limit'); await browser.close(); server.close(); process.exit(3); }, 540000);
  const t0 = Date.now(), T = () => `${((Date.now() - t0) / 1000).toFixed(0)}s`;
  try {
    const page = await (await browser.newContext({ viewport: { width: 1280, height: 1100 }, deviceScaleFactor: 1 })).newPage();
    page.on('pageerror', e => console.error('pageerror', e.message));
    page.on('console', m => { if (m.type() === 'error') console.error('console', m.text().slice(0, 300)); });
    const film = path.relative(repo, r.seg.boot);
    await page.goto(`http://127.0.0.1:${server.address().port}/__camtry/camtry.html?film=${film}&w=${flag('w', 360)}&h=${flag('h', 640)}`);
    await page.waitForFunction(() => window.__ct?.ready || window.__ctError, null, { timeout: 300000, polling: 200 });
    const err = await page.evaluate(() => window.__ctError); if (err) throw new Error(err);
    console.error(T(), 'engine ready', film);
    const cams = await page.evaluate(([A, B]) => window.__ct.film(A, B), [A, B]);
    const samples = J.takes.filter(t => t.frames[1] >= A && t.frames[0] <= B).flatMap(t => { const a = Math.max(A, t.frames[0]), b = Math.min(B, t.frames[1]); return [a, Math.round((a + b) / 2), b]; });
    const set = await page.evaluate(fs => window.__ct.setup(fs), samples);
    console.error(T(), 'static meshes', set.proxies, 'buildings', set.buildings);
    const tables = await variantCams(page, V, cams, A, B, r.change);
    const strip = { A, B, change: r.change, cuts, takes: J.takes.filter(t => t.frames[1] >= A && t.frames[0] <= B) };
    const res = Object.fromEntries(V.map(v => [v.id, []])), frames = path.join(OUT, 'frames');
    fs.rmSync(frames, { recursive: true, force: true }); fs.mkdirSync(frames);
    for (let f = A; f <= B; f++) {
      const t = await page.evaluate(([cs, labels, TW, TH, BAR, STRIP, f, strip]) => window.__ct.tile(f, cs, labels, TW, TH, BAR, STRIP, strip), [tables.map(x => x[f]), V.map(v => v.label), TW, TH, BAR, STRIP, f, strip]);
      fs.writeFileSync(path.join(frames, `f${String(f - A).padStart(4, '0')}.jpg`), Buffer.from(t.img.split(',')[1], 'base64'));
      t.m.forEach((m, i) => res[V[i].id].push({ f, ...m }));
      if ((f - A) % 50 === 0) console.error(T(), 'frame', f);
    }
    // the top view: one row per take, one column per variant (each take is its own place; a cut is a jump)
    const rows = [];
    for (const tk of strip.takes) {
      const [a, b] = [Math.max(A, tk.frames[0]), Math.min(B, tk.frames[1])], fr = Array.from({ length: b - a + 1 }, (_, k) => a + k), row = [];
      const changed = fr.some(f => f >= C0 && f <= C1);
      for (let i = 0; i < V.length; i++) {
        const byF = Object.fromEntries(res[V[i].id].map(x => [x.f, x.touch]));
        const img = await page.evaluate(a => window.__ct.map(...a), [fr.map(f => tables[i][f].pos), fr.map(f => byF[f]), fr.map(f => cams[f].subject?.head ?? null),
          `${V[i].id} · take ${tk.n} ${a}-${b}${changed || !i ? '' : ' · như phim'}`, TW, TH, BAR, fr.map(f => !tables[i][f].keep)]);
        const p = path.join(OUT, `top-${tk.n}-${V[i].id}.jpg`); fs.writeFileSync(p, Buffer.from(img.split(',')[1], 'base64')); row.push(p);
      }
      rows.push(row);
    }
    const ff = a => { const x = run('ffmpeg', ['-loglevel', 'error', '-y', ...a]); if (x.status) throw new Error('ffmpeg failed'); };
    ff(['-framerate', '30', '-i', path.join(frames, 'f%04d.jpg'), '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-crf', '20', path.join(OUT, 'variants.mp4')]);
    const tops = rows.flat(), nV = V.length, nR = rows.length;
    const grid = rows.flatMap((row, y) => row.map((_, x) => `${x * TW}_${y * (TH + BAR)}`)).join('|');
    ff([...tops.flatMap(t => ['-i', t]), '-filter_complex', tops.length > 1 ? `xstack=inputs=${tops.length}:layout=${grid}` : 'null', path.join(OUT, 'top.jpg')]);
    for (const t of tops) fs.rmSync(t);
    ff(['-ss', String(((C0 + C1) / 2 - A) / 30), '-i', path.join(OUT, 'variants.mp4'), '-frames:v', '1', path.join(OUT, 'poster.jpg')]);
    fs.rmSync(frames, { recursive: true, force: true });
    const changedOnly = Object.fromEntries(V.map(v => [v.id, res[v.id].filter(x => x.f >= C0 && x.f <= C1)]));
    const rec = recommend(V, summary(V, changedOnly));
    J.numbers = summary(V, changedOnly); J.pick = rec.id; J.pickManual = rec.manual; J.definitions = DEFS;
    J.manualNote = manualNote(J);
    J.renderSeconds = Math.round((Date.now() - t0) / 1000); J.size = [+flag('w', 360), +flag('h', 640)]; J.topGrid = { rows: nR, cols: nV };
    fs.writeFileSync(path.join(OUT, 'camtry.json'), JSON.stringify(J, null, 1));
    fs.writeFileSync(path.join(OUT, 'section.html'), section(J));
    for (const v of V) { const n = J.numbers[v.id]; console.log(`${v.id} chạm ${n.wallTouchFrames.length} · lấp ${n.wallFillFrames.length} · gần nhất ${n.minWallDist} m · cao ${n.meanCamHeight} m · nhân vật ${n.subjectScreenHeightMean ?? '-'} · mặt tiền ${n.facadeShareMean}`); }
    if (J.manualNote) console.log(J.manualNote);
    console.log(`Em đề xuất ${J.pick}${J.pickManual ? ' (áp tay)' : ''}. ${B - A + 1} khung x ${V.length} phương án, ${J.renderSeconds} s. out ${OUT}`);
  } finally { clearTimeout(kill); await browser.close(); server.close(); console.error(T(), 'done'); }
}

// every variant's camera per frame (Blender metres); outside the change range every variant is the film camera
async function variantCams(page, V, cams, A, B, [C0, C1]) {
  const wallAt = {};
  for (const up of [...new Set(V.filter(v => v.away && v.from === 'wall').map(v => v.up || 0))]) {
    const raw = await page.evaluate(a => a[0].map(p => window.__ct.offWall(p)), [Array.from({ length: B - A + 1 }, (_, k) => { const c = cams[A + k]; return [c.pos[0], c.pos[1], c.pos[2] + up]; })]);
    wallAt[up] = raw.map((_, k) => { let x = 0, y = 0; for (let j = k - 8; j <= k + 8; j++) if (raw[j]) { x += raw[j][0]; y += raw[j][1]; } const l = Math.hypot(x, y); return l ? [x / l, y / l] : null; });
  }
  return V.map(v => {
    const t = {};
    for (let f = A; f <= B; f++) {
      const c = cams[f], pos = [...c.pos], aim = [...c.aim], up = v.up || 0;
      const keep = f < C0 || f > C1 || (!up && !v.away && !v.closer && (!v.aim || v.aim === 'film'));
      if (keep) { t[f] = { pos, aim, fov: c.fov, subject: c.subject, keep }; continue; }
      pos[2] += up; if (v.aim === 'lift') aim[2] += up; if (v.aim === 'hero' && c.subject) aim.splice(0, 3, ...c.subject.aim);
      if (v.away) { const b = [c.pos[0] - c.aim[0], c.pos[1] - c.aim[1]], l = Math.hypot(...b) || 1, d = (v.from === 'wall' && wallAt[up]?.[f - A]) || [b[0] / l, b[1] / l];
        pos[0] += d[0] * v.away; pos[1] += d[1] * v.away; }
      if (v.closer) { const d = aim.map((x, i) => x - pos[i]), l = Math.hypot(...d), k = Math.min(v.closer, l - 0.5) / l; for (let i = 0; i < 3; i++) pos[i] += d[i] * k; }
      t[f] = { pos, aim, fov: c.fov, subject: c.subject, keep };
    }
    return t;
  });
}

const DEFS = {
  building: 'a static set mesh (same place at the first, middle and last frame, visible in the middle) taller than 2 m, top above 2.5 m, wider than 1.5 m',
  wallTouch: 'the camera inside a building mesh (ray parity, 6 axes) or within 0.3 m of one (64 rays from the lens)',
  wallFill: 'more than 50% of an 18 x 32 ray grid through the frame hits a building mesh closer than 4 m',
  facadeShare: 'share of the same grid that hits a building mesh at any distance up to 80 m',
  minWallDist: 'nearest building mesh, 64 rays up to 15 m (99 = none)',
  subjectScreenHeight: "the lead's head top to lowest foot on screen, as a share of the frame height",
  away: "horizontal, off the nearest building (32 rays, 12 m, smoothed over +-8 frames), or back from the film's aim point",
};
const mean = (r, k) => { const xs = r.map(x => x[k]).filter(x => x != null); return xs.length ? +(xs.reduce((s, x) => s + x, 0) / xs.length).toFixed(3) : null; };
function summary(V, res) {
  return Object.fromEntries(V.map(v => { const r = res[v.id];
    return [v.id, { label: v.label, wallTouchFrames: r.filter(x => x.touch).map(x => x.f), wallFillFrames: r.filter(x => x.wallFill > 0.5).map(x => x.f),
      minWallDist: Math.min(...r.map(x => x.minD)), meanCamHeight: mean(r, 'z'), subjectScreenHeightMean: mean(r, 'subjectH'),
      facadeShareMean: mean(r, 'facade'), facadeShareMax: Math.max(...r.map(x => x.facade)),
      closeWalls: Object.values(Object.fromEntries(r.filter(x => x.minD < 1).map(x => [x.who, { mesh: x.who, top: x.top }]))),
      perFrame: r.map(({ f, minD, wallFill, facade, subjectH, inside }) => ({ f, minD, wallFill, facade, subjectH, inside })) }]; }));
}
// the recommended variant still touches a wall that a variant `pick` cannot write clears: say which, and where
function manualNote(J) {
  const touch = id => J.numbers[id].wallTouchFrames, clears = J.variants.filter(v => !v.applies && touch(v.id).length < touch(J.pick).length);
  if (!clears.length || !touch(J.pick).length) return null;
  const f = touch(J.pick);
  return `${J.pick} vẫn chạm tường ${f.length} khung (${f[0]}-${f.at(-1)}); chỉ ${clears.map(v => v.id).join(', ')} hết chạm, phải sửa máy bằng tay.`;
}
const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
function section(J) {
  const n = J.change.join('-'), d = `camtry-${J.seg}-${n}`, N = J.numbers, rec = J.pickManual ? 'Em đề xuất (áp tay)' : 'Em đề xuất';
  const rows = J.variants.map(v => { const x = N[v.id];
    return `<tr><td class="c">${esc(v.label)}${v.applies ? '' : ' <span class="muted">(xem được, áp tay)</span>'}</td><td>${x.wallTouchFrames.length}</td><td>${x.wallFillFrames.length}</td><td>${x.minWallDist > 15 ? '&gt;15' : x.minWallDist}</td><td>${x.meanCamHeight}</td><td>${x.subjectScreenHeightMean ?? '—'}</td><td>${x.facadeShareMean}</td></tr>`; }).join('');
  const opts = J.variants.map(v => `<button class="opt" data-d="${d}" data-o="${v.id}">${v.id === J.pick ? `<span class="rec">${rec}</span>` : ''}<b>${esc(v.label)}</b><span>chạm ${N[v.id].wallTouchFrames.length} khung · lấp ${N[v.id].wallFillFrames.length} khung${v.applies ? '' : ' · xem được, áp tay'}</span></button>`).join('\n      ');
  return `<section>
    <h2 id="${d}">Thử góc máy · ${esc(J.seg)} ${J.window.join('-')}</h2>
    <p class="muted">${esc(J.readback)}</p>${J.manualNote ? `\n    <p><b>${esc(J.manualNote)}</b></p>` : ''}
    <figure class="pc"><video src="variants.mp4" poster="poster.jpg" controls playsinline preload="metadata" style="aspect-ratio:auto"></video><figcaption>Cả đoạn ${J.window.join('-')}, 30 khung/giây, máy của phim render từng phương án cạnh nhau. Thanh dưới: vàng là khung ${n} phương án đổi, vạch trắng là chỗ cắt, kim trắng là khung đang xem. Ngoài khung vàng mọi phương án là máy của phim. Chữ đỏ: máy chạm tường.</figcaption></figure>
    <figure class="pc"><img src="top.jpg" alt="Nhìn từ trên: đường máy quay từng phương án" style="width:100%;display:block"><figcaption>Nhìn từ trên, mỗi hàng một take, mỗi cột một phương án. Vàng: máy quay ở khung đổi (vàng mờ: như phim). Xanh: nhân vật. Đỏ: khung chạm tường. Nhà sáng hơn là nhà cao hơn.</figcaption></figure>
    <div class="scroll"><table><caption class="muted">Số đo trên khung đổi ${n}.</caption><thead><tr><th>Phương án</th><th>Khung chạm tường</th><th>Khung tường lấp hình</th><th>Gần tường nhất (m)</th><th>Máy cao (m)</th><th>Nhân vật cao (phần khung)</th><th>Mặt tiền nhà (phần khung)</th></tr></thead><tbody>${rows}</tbody></table></div>
    <div class="dec"><div class="q">Anh chọn góc máy nào cho khung ${n}?</div><div class="opts">
      ${opts}</div>
      <textarea class="kn" data-id="dec-${d}" placeholder="Ghi chú"></textarea><div class="mini" data-m="${d}"></div></div>
  </section>
`;
}

if (words[0] === 'pick') await pick(words[1], words[2]);
else await camtry(words.join(' '));
