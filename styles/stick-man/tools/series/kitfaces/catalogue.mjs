// The kit face catalogue as a document: every face a character can use (engine/facestyles/s2.js PURPOSE, ALIASES),
// what a story uses it for and its emotion family (tools/gates/facebeat.mjs FAMILY). The sheet that shows them is
// review/face-sheet.jpg in this folder.
//   node styles/stick-man/tools/series/kitfaces/catalogue.mjs            -> CATALOGUE.md (stick-kitfaces.test.mjs keeps it in step)
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath, pathToFileURL } from 'node:url';

export async function catalogue() {
  globalThis.location ??= { search: '' };
  const { ALIASES, PURPOSE } = await import('#engine/facestyles/s2.js');
  const { FAMILY } = await import('#tools/gates/facebeat.mjs');
  const fam = n => Object.entries(FAMILY).find(([, l]) => l.includes(n) || l.includes(n.replace(/^[yc]_/, '')))?.[0] ?? '';
  const others = d => Object.entries(ALIASES).filter(([, t]) => t === d).map(([a]) => a);
  const rows = [];
  for (const n of Object.keys(PURPOSE)) if (!ALIASES[n]) rows.push([n, others(n), PURPOSE[n], fam(n)]);
  for (const [n, t] of Object.entries(ALIASES)) if (PURPOSE[n] && !rows.some(r => r[1].includes(n))) rows.push([n, [t, ...others(t).filter(a => a !== n)], PURPOSE[n], fam(n)]);
  return ['# Kit face catalogue', '',
    `Every face a stick-man character can use, all in the H2 V2.1 style (Kai 25/11: no dot faces). ${rows.length} faces; the`,
    'other names draw the same face. The sheet: `review/face-sheet.jpg` in this folder, approved once for every film.',
    'Generated by `node styles/stick-man/tools/series/kitfaces/catalogue.mjs`.', '',
    '| Face | Also called | For | Family |', '| --- | --- | --- | --- |',
    ...rows.map(([n, a, p, f]) => `| \`${n}\` | ${a.map(x => `\`${x}\``).join(', ')} | ${p} | ${f} |`)].join('\n') + '\n';
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), 'CATALOGUE.md');
  fs.writeFileSync(out, await catalogue());
  console.log(`${path.relative(process.cwd(), out)} written`);
}
