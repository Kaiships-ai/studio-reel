// "Thử góc máy": a director's note about the camera -> 3-4 camera variants rendered by the film's own engine (headless
// Chrome, real GPU), side by side, with a top view and wall numbers; then the picked one goes into the camera anchors.
//   node styles/stick-man/tools/camtry.mjs "đoạn đua xe, máy quay dính tường nhà, nâng lên chút"
//        [--film films/<slug>] [--out <dir>] [--frames A-B] [--max 100] [--variants v.json] [--w 540 --h 960] [--dry 1]
//   node styles/stick-man/tools/camtry.mjs pick <out dir> <V1> [--dry 1]
// The first line printed is the readback ("Em hiểu là: phim …, đoạn …, khung A-B, máy quay …"). The film defaults to the
// newest one in ./films; the segment, take, frames and anchors come from its generated act tables (camtry-core.mjs).
// Writes to --out (default <film>/review/camtry/<SEG>-<A>-<B>/): variants.mp4, top.jpg, camtry.json (the readback, the
// variants and the numbers per variant), section.html (clip, top view, numbers, a pick box for the stage page).
// `pick` writes the variant's change into the anchors file (<round>/xfer/<SEG>.json) and reruns every generator that reads
// it (the `// generated by` line of <round>/gen/*.js); --dry 1 prints the change only. Film and kit files are read only
// until `pick`.
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
import { run } from '../../../kit/env.mjs';
import { filmIndex, findFilm, resolve, variantsFromWords, readback, applyPick, formatSpec, parseGen, recommend } from './camtry-core.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
if (!argv.length || argv.includes('--help')) {
  console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').filter(l => l.startsWith('//')).map(l => l.slice(3)).join('\n'));
  process.exit(argv.length ? 0 : 2);
}
const flag = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 ? argv[i + 1] : d; };
const words = argv.filter((a, i) => !a.startsWith('--') && !(i && argv[i - 1].startsWith('--')));

async function pick(outDir, id) {
  const J = JSON.parse(fs.readFileSync(path.join(outDir, 'camtry.json'), 'utf8')), v = J.variants.find(x => x.id === id);
  if (!v) { console.error(`no variant ${id} in ${outDir} (${J.variants.map(x => x.id).join(', ')})`); process.exit(2); }
  if (!J.xfer) { console.error(`đoạn ${J.seg} không có file neo xfer: máy quay nằm trong file act, sửa tay theo số ở camtry.json`); process.exit(1); }
  const res = applyPick(JSON.parse(fs.readFileSync(J.xfer, 'utf8')), v, J.window);
  if (!res.ok) { console.error(`${v.label}: chưa áp tự động được: ${res.unsupported.join('; ')}`); process.exit(1); }
  if (!res.changed.length) { console.log(`${v.label}: không có gì đổi`); return; }
  for (const c of res.changed) console.log(`neo ${c.f0}-${c.f1 - 1}: dz ${c.dz0} -> ${c.dz} (cả cửa sổ neo, khung ${c.f0}-${c.f1 - 1})`);
  if (flag('dry')) return;
  fs.writeFileSync(J.xfer, formatSpec(res.spec));
  const film = J.film, round = path.dirname(path.dirname(J.xfer)), rel = path.relative(film, J.xfer), repo = path.dirname(path.dirname(film));
  for (const f of fs.readdirSync(path.join(round, 'gen')).filter(x => x.endsWith('.js'))) {
    const head = fs.readFileSync(path.join(round, 'gen', f), 'utf8').split('\n', 1)[0], g = parseGen(head);
    if (!g.tool || !head.includes(` ${rel}`)) continue;
    const args = [path.join(film, g.tool), ...(g.seg && g.seg !== 'from' ? [g.seg] : [])];
    console.log('regenerate:', path.relative(repo, args[0]), args.slice(1).join(' '));
    const r = run('node', args, { cwd: repo });
    if (r.status) process.exit(r.status);
  }
}

async function camtry(request) {
  const filmDir = flag('film') ? path.resolve(flag('film')) : findFilm(path.resolve('films'), request);
  if (!filmDir) { console.error('no film in ./films (give --film films/<slug>)'); process.exit(2); }
  const index = filmIndex(filmDir), r = resolve(request, index, { max: +flag('max', 100) });
  if (flag('frames')) { r.window = flag('frames').split('-').map(Number); }
  console.log(readback(r));
  if (!r.seg) process.exit(1);
  const V = flag('variants') ? JSON.parse(fs.readFileSync(flag('variants'), 'utf8')) : variantsFromWords(request);
  const [A, B] = r.window, OUT = path.resolve(flag('out', path.join(filmDir, 'review', 'camtry', `${r.seg.id}-${A}-${B}`)));
  fs.mkdirSync(OUT, { recursive: true });
  const J = { request, readback: readback(r), film: filmDir, seg: r.seg.id, segFrames: r.seg.frames, take: r.take, window: r.window,
    xfer: r.seg.xfer, anchors: r.anchors, boot: r.seg.boot, why: r.why, variants: V };
  fs.writeFileSync(path.join(OUT, 'camtry.json'), JSON.stringify(J, null, 1));
  for (const v of V) console.log(' ', v.label);
  if (flag('dry')) { console.log('out', OUT); return; }

  const repo = path.dirname(path.dirname(filmDir)), TW = 270, TH = 480, BAR = 40;
  const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.json': 'application/json', '.wasm': 'application/wasm', '.png': 'image/png', '.jpg': 'image/jpeg', '.ttf': 'font/ttf', '.woff2': 'font/woff2' };
  const server = http.createServer((q, res) => {
    const u = decodeURIComponent(new URL(q.url, 'http://x').pathname);
    const f = u.startsWith('/__camtry/') ? path.join(HERE, u.slice(10)) : path.join(repo, u);
    if (!(f.startsWith(repo) || f.startsWith(HERE)) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404).end(); return; }
    res.writeHead(200, { 'Content-Type': MIME[path.extname(f)] || 'application/octet-stream' }); fs.createReadStream(f).pipe(res);
  });
  await new Promise(ok => server.listen(0, '127.0.0.1', ok));
  const { chromium } = await import('playwright-core');
  const browser = await chromium.launch({ args: ['--use-angle=metal', '--ignore-gpu-blocklist', '--enable-gpu-rasterization'] });
  const kill = setTimeout(async () => { console.error('camtry: 9 min limit'); await browser.close(); server.close(); process.exit(3); }, 540000);
  const t0 = Date.now(), T = () => `${((Date.now() - t0) / 1000).toFixed(0)}s`;
  try {
    const page = await (await browser.newContext({ viewport: { width: 1280, height: 1100 }, deviceScaleFactor: 1 })).newPage();
    page.on('pageerror', e => console.error('pageerror', e.message));
    page.on('console', m => { if (m.type() === 'error') console.error('console', m.text().slice(0, 300)); });
    const film = path.relative(repo, r.seg.boot);
    await page.goto(`http://127.0.0.1:${server.address().port}/__camtry/camtry.html?film=${film}&w=${flag('w', 540)}&h=${flag('h', 960)}`);
    await page.waitForFunction(() => window.__ct?.ready || window.__ctError, null, { timeout: 300000, polling: 200 });
    const err = await page.evaluate(() => window.__ctError); if (err) throw new Error(err);
    console.error(T(), 'engine ready', film);
    const cams = await page.evaluate(([A, B]) => window.__ct.film(A, B), [A, B]);
    const set = await page.evaluate(([A, B, P]) => window.__ct.setup(A, B, P), [A, B, Math.round((A + B) / 2)]);
    console.error(T(), 'static meshes', set.proxies, 'buildings', set.buildings);
    const tables = await variantCams(page, V, cams, A, B);
    const res = Object.fromEntries(V.map(v => [v.id, []])), frames = path.join(OUT, 'frames');
    fs.rmSync(frames, { recursive: true, force: true }); fs.mkdirSync(frames);
    for (let f = A; f <= B; f++) {
      const t = await page.evaluate(([cs, labels, TW, TH, BAR, f]) => window.__ct.tile(f, cs, labels, TW, TH, BAR), [tables.map(x => x[f]), V.map(v => v.label), TW, TH, BAR, f]);
      fs.writeFileSync(path.join(frames, `f${String(f - A).padStart(4, '0')}.jpg`), Buffer.from(t.img.split(',')[1], 'base64'));
      t.m.forEach((m, i) => res[V[i].id].push({ f, ...m }));
      if ((f - A) % 25 === 0) console.error(T(), 'frame', f);
    }
    const tops = [];
    for (let i = 0; i < V.length; i++) {
      const fr = Object.keys(tables[i]).map(Number).sort((p, q) => p - q);
      const img = await page.evaluate(a => window.__ct.map(...a), [fr.map(f => tables[i][f].pos), res[V[i].id].map(x => x.touch), fr.map(f => cams[f].subject?.head ?? null), V[i].label, TW, TH, BAR]);
      const p = path.join(OUT, `top-${V[i].id}.jpg`); fs.writeFileSync(p, Buffer.from(img.split(',')[1], 'base64')); tops.push(p);
    }
    const ff = a => { const x = run('ffmpeg', ['-loglevel', 'error', '-y', ...a]); if (x.status) throw new Error('ffmpeg failed'); };
    ff(['-framerate', '30', '-i', path.join(frames, 'f%04d.jpg'), '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-crf', '20', path.join(OUT, 'variants.mp4')]);
    ff([...tops.flatMap(t => ['-i', t]), '-filter_complex', V.length > 1 ? `hstack=${V.length}` : 'null', path.join(OUT, 'top.jpg')]);
    ff(['-ss', String((B - A) / 60), '-i', path.join(OUT, 'variants.mp4'), '-frames:v', '1', path.join(OUT, 'poster.jpg')]);
    fs.rmSync(frames, { recursive: true, force: true });
    J.numbers = summary(V, res); J.pick = recommend(V, J.numbers); J.definitions = DEFS;
    fs.writeFileSync(path.join(OUT, 'camtry.json'), JSON.stringify(J, null, 1));
    fs.writeFileSync(path.join(OUT, 'section.html'), section(J));
    for (const v of V) { const n = J.numbers[v.id]; console.log(`${v.id} chạm ${n.wallTouchFrames.length} · lấp ${n.wallFillFrames.length} · gần nhất ${n.minWallDist} m · cao ${n.meanCamHeight} m · nhân vật ${n.subjectScreenHeightMean ?? '-'} · mặt tiền ${n.facadeShareMean}`); }
    console.log(`Em đề xuất ${J.pick}. out ${OUT}`);
  } finally { clearTimeout(kill); await browser.close(); server.close(); console.error(T(), 'done'); }
}

// every variant's camera per frame (Blender metres); `keep` renders the film camera itself
async function variantCams(page, V, cams, A, B) {
  const wallAt = {};
  for (const up of [...new Set(V.filter(v => v.away && v.from === 'wall').map(v => v.up || 0))]) {
    const raw = await page.evaluate(a => a[0].map(p => window.__ct.offWall(p)), [Array.from({ length: B - A + 1 }, (_, k) => { const c = cams[A + k]; return [c.pos[0], c.pos[1], c.pos[2] + up]; })]);
    wallAt[up] = raw.map((_, k) => { let x = 0, y = 0; for (let j = k - 8; j <= k + 8; j++) if (raw[j]) { x += raw[j][0]; y += raw[j][1]; } const l = Math.hypot(x, y); return l ? [x / l, y / l] : null; });
  }
  return V.map(v => {
    const t = {};
    for (let f = A; f <= B; f++) {
      const c = cams[f], pos = [...c.pos], aim = [...c.aim], up = v.up || 0;
      const keep = !up && !v.away && !v.closer && (!v.aim || v.aim === 'film');
      pos[2] += up; if (v.aim === 'lift') aim[2] += up; if (v.aim === 'hero' && c.subject) aim.splice(0, 3, ...c.subject.aim);
      if (v.away) { const b = [c.pos[0] - c.aim[0], c.pos[1] - c.aim[1]], l = Math.hypot(...b) || 1, d = (v.from === 'wall' && wallAt[up]?.[f - A]) || [b[0] / l, b[1] / l];
        pos[0] += d[0] * v.away; pos[1] += d[1] * v.away; }
      if (v.closer) { const d = aim.map((x, i) => x - pos[i]), l = Math.hypot(...d), k = Math.min(v.closer, l - 0.5) / l; for (let i = 0; i < 3; i++) pos[i] += d[i] * k; }
      t[f] = { pos, aim, fov: c.fov, subject: c.subject, keep };
    }
    return t;
  });
}

const DEFS = {
  building: 'a static set mesh (same place at the first, middle and last frame, visible in the middle) taller than 2 m, top above 2.5 m, wider than 1.5 m',
  wallTouch: 'the camera inside a building mesh (ray parity, 6 axes) or within 0.3 m of one (64 rays from the lens)',
  wallFill: 'more than 50% of an 18 x 32 ray grid through the frame hits a building mesh closer than 4 m',
  facadeShare: 'share of the same grid that hits a building mesh at any distance up to 80 m',
  minWallDist: 'nearest building mesh, 64 rays up to 15 m (99 = none)',
  subjectScreenHeight: "the lead's head top to lowest foot on screen, as a share of the frame height",
  away: "horizontal, off the nearest building (32 rays, 12 m, smoothed over +-8 frames), or back from the film's aim point",
};
const mean = (r, k) => { const xs = r.map(x => x[k]).filter(x => x != null); return xs.length ? +(xs.reduce((s, x) => s + x, 0) / xs.length).toFixed(3) : null; };
function summary(V, res) {
  return Object.fromEntries(V.map(v => { const r = res[v.id];
    return [v.id, { label: v.label, wallTouchFrames: r.filter(x => x.touch).map(x => x.f), wallFillFrames: r.filter(x => x.wallFill > 0.5).map(x => x.f),
      minWallDist: Math.min(...r.map(x => x.minD)), meanCamHeight: mean(r, 'z'), subjectScreenHeightMean: mean(r, 'subjectH'),
      facadeShareMean: mean(r, 'facade'), facadeShareMax: Math.max(...r.map(x => x.facade)),
      closeWalls: Object.values(Object.fromEntries(r.filter(x => x.minD < 1).map(x => [x.who, { mesh: x.who, top: x.top }]))),
      perFrame: r.map(({ f, minD, wallFill, facade, subjectH, inside }) => ({ f, minD, wallFill, facade, subjectH, inside })) }]; }));
}
const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
function section(J) {
  const n = J.window.join('-'), d = `camtry-${J.seg}-${n}`, N = J.numbers;
  const rows = J.variants.map(v => { const x = N[v.id];
    return `<tr><td class="c">${esc(v.label)}</td><td>${x.wallTouchFrames.length}</td><td>${x.wallFillFrames.length}</td><td>${x.minWallDist > 15 ? '&gt;15' : x.minWallDist}</td><td>${x.meanCamHeight}</td><td>${x.subjectScreenHeightMean ?? '—'}</td><td>${x.facadeShareMean}</td></tr>`; }).join('');
  const opts = J.variants.map(v => `<button class="opt" data-d="${d}" data-o="${v.id}">${v.id === J.pick ? '<span class="rec">Em đề xuất</span>' : ''}<b>${esc(v.label)}</b><span>chạm ${N[v.id].wallTouchFrames.length} khung · lấp ${N[v.id].wallFillFrames.length} khung</span></button>`).join('\n      ');
  return `<section>
    <h2 id="${d}">Thử góc máy · ${esc(J.seg)} ${n}</h2>
    <p class="muted">${esc(J.readback)}</p>
    <figure class="pc"><video src="variants.mp4" poster="poster.jpg" controls playsinline preload="metadata" style="aspect-ratio:auto"></video><figcaption>Máy của phim render từng phương án, cạnh nhau. Dòng chữ đỏ: máy chạm tường.</figcaption></figure>
    <figure class="pc"><img src="top.jpg" alt="Nhìn từ trên: đường máy quay từng phương án" style="width:100%;display:block"><figcaption>Nhìn từ trên. Vàng: máy quay. Xanh: nhân vật. Đỏ: khung chạm tường. Nhà sáng hơn là nhà cao hơn.</figcaption></figure>
    <div class="scroll"><table><thead><tr><th>Phương án</th><th>Khung chạm tường</th><th>Khung tường lấp hình</th><th>Gần tường nhất (m)</th><th>Máy cao (m)</th><th>Nhân vật cao (phần khung)</th><th>Mặt tiền nhà (phần khung)</th></tr></thead><tbody>${rows}</tbody></table></div>
    <div class="dec"><div class="q">Anh chọn góc máy nào cho khung ${n}?</div><div class="opts">
      ${opts}</div>
      <textarea class="kn" data-id="dec-${d}" placeholder="Ghi chú"></textarea><div class="mini" data-m="${d}"></div></div>
  </section>
`;
}

if (words[0] === 'pick') await pick(words[1], words[2]);
else await camtry(words.join(' '));
